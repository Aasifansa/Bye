    # USER DATA
    async def present_user(self, user_id: int):
        found = await self.user_data.find_one({'_id': user_id})
        return bool(found)

    async def add_user(self, user_id: int):
        if not await self.present_user(user_id):
            await self.user_data.insert_one({'_id': user_id, 'joined_date': datetime.utcnow()})
        return

    async def full_userbase(self):
        user_docs = await self.user_data.find().to_list(length=None)
        user_ids = [doc['_id'] for doc in user_docs]
        return user_ids

    async def del_user(self, user_id: int):
        await self.user_data.delete_one({'_id': user_id})
        return


    # ================= PAID / PREMIUM USER DATA =================
    async def add_premium(self, user_id: int, expiry_date: datetime, plan_name: str = "VIP Plan"):
        """User ko exact UTC expiry ke sath Paid/VIP access deta hai"""
        await self.user_data.update_one(
            {'_id': int(user_id)},
            {
                '$set': {
                    'is_premium': True,
                    'expiry_date': expiry_date,
                    'plan_name': plan_name,
                    'premium_joined': datetime.utcnow()
                }
            },
            upsert=True
        )

    async def remove_premium(self, user_id: int):
        """User ka Paid/VIP access khatam karta hai"""
        await self.user_data.update_one(
            {'_id': int(user_id)},
            {'$set': {'is_premium': False, 'expiry_date': None, 'plan_name': None}}
        )

    async def check_paid_access(self, user_id: int):
        """Check karta hai ki user ke paas active Paid/VIP access hai ya nahi"""
        user = await self.user_data.find_one({'_id': int(user_id)})
        if user and user.get('is_premium', False):
            expiry = user.get('expiry_date')
            if expiry and expiry > datetime.utcnow():
                ist_expiry = expiry + timedelta(hours=5, minutes=30)
                return True, ist_expiry
            else:
                await self.remove_premium(user_id)
                return False, None
        return False, None

    async def get_all_prem_users(self):
        """Saare active premium users ki list nikalne ke liye"""
        now = datetime.utcnow()
        cursor = self.user_data.find({'is_premium': True, 'expiry_date': {'$gt': now}})
        docs = await cursor.to_list(length=None)
        formatted_users = []
        for doc in docs:
            exp_utc = doc.get('expiry_date')
            exp_ist = (exp_utc + timedelta(hours=5, minutes=30)) if exp_utc else None
            formatted_users.append({
                'user_id': doc['_id'],
                'expires_at': exp_ist,
                'plan': doc.get('plan_name', 'VIP')
            })
        return formatted_users
